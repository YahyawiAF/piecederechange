function inferMaker(name: string): string {
  return MAKER_HINTS.find((m) => name.toLowerCase().includes(m.toLowerCase())) ?? "OEM";
}

function inferPosition(name: string): string | null {
  if (/avant|front/i.test(name)) return "Avant";
  if (/arri[eè]re|rear/i.test(name)) return "Arrière";
  return null;
}

function defaultSpecs(p: {
  categoryId: string;
  partName: string;
  warranty: string | null;
  condition: Part["condition"];
}): { label: string; value: string }[] {
  const pos = inferPosition(p.partName);
  if (p.categoryId === "c-freinage") {
    return [
      { label: "Matière", value: "Céramique" },
      { label: "Position", value: pos ?? "Avant" },
      { label: "Épaisseur", value: "17 mm" },
      { label: "Capteur d'usure", value: "Oui" },
    ];
  }
  if (p.categoryId === "c-filtres") {
    return [
      { label: "Type", value: "Papier plissé" },
      { label: "Diamètre", value: "68 mm" },
      { label: "Hauteur", value: "85 mm" },
    ];
  }
  if (p.categoryId === "c-electricite") {
    return [
      { label: "Électrode", value: "Iridium" },
      { label: "Écartement", value: "0.9 mm" },
    ];
  }
  if (p.categoryId === "c-transmission") {
    return [
      { label: "Renfort", value: "Aramide" },
      { label: "Longueur", value: "918 mm" },
    ];
  }
  return [
    { label: "Garantie", value: p.warranty ?? "6 mois" },
    { label: "Condition", value: p.condition },
  ];
}

